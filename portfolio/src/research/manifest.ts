// The canonical project inventory. One record per project, one stable id, used by the city, the
// search, the filters, the timeline and the case-study routes alike.
//
// What this file may say: what a project is, what was built, and how each claim can be checked.
// What it may NOT say: whether a project is healthy right now. Runtime status (running, failed,
// stale) is derived from verified events in events.ts; nothing here can override it. Presentation
// (colours, plots on the city grid) lives in layout.ts.
//
// Evidence grades, strongest first. A milestone is only drawn as a lit floor if its grade is one of
// SHIPPED; "unverified" floors are hatched and "planned" floors are scaffolding.
//   deployed     running in a deployed application a visitor can open
//   validated    an analytical result checked against an independent reference
//   result       a research output generated by a reproducible script in this repository
//   tested       covered by an automated check that passes in this repository
//   implemented  the code exists in this repository
//   unverified   claimed, but the evidence is outside this repository and wasn't checked
//   planned      not built

export type Evidence = "deployed" | "validated" | "result" | "tested" | "implemented" | "unverified" | "planned";
export const SHIPPED: Evidence[] = ["deployed", "validated", "result", "tested", "implemented"];

