export interface Milestone {
  label: string;
  evidence: Evidence;
  /** `repo:<path>` (checked to exist by the manifest test), a site path, or an https URL */
  ref?: string;
}

export interface Agent {
  name: string;
  kind: AgentKind;
  duty: string;
  /** the job's last known output, and where that claim comes from */
  output: string;
  /** "verified" only when the job's definition is in this repository or its runs are public */
  verification: "verified" | "not-verified";
  source?: string;
}

export interface Link {
  label: string;
  href: string;
  kind: "page" | "repo" | "report" | "data" | "workbook" | "demo";
  /** `station` makes the link scroll the home page instead of loading a URL when already there */
  station?: "model" | "jarvis";
}

export interface Project {
  id: ProjectId;
  title: string;
  summary: string;
  problem: string;
  user: string;
  district: DistrictId;
  category: CategoryId;
  tags: string[];
  /** where the data comes from, and how old it may get before it counts as stale */
  data: { label: string; asOf?: string; staleAfterDays?: number };
  /** the automated pipeline whose verified runs drive this project's execution status */
  pipeline: "brain" | "jarvis-ci" | "none";
  /** repository paths whose commits count as this project's change history */
  paths: string[];
  milestones: Milestone[];
  limitations: string[];
  agents: Agent[];
  links: Link[];
  repo?: string;
  /** false: don't link source paths from the case study (the owner describes this code as private) */
  sourcePublic?: boolean;
}

