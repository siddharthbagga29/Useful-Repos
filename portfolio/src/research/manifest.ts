export const project = (id: string): Project | undefined => PROJECTS.find((p) => p.id === id);
export const shipped = (p: Project) => p.milestones.filter((m) => SHIPPED.includes(m.evidence));
export const pending = (p: Project) => p.milestones.filter((m) => m.evidence === "planned");
export const unverified = (p: Project) => p.milestones.filter((m) => m.evidence === "unverified");
/** share of milestones with evidence in this repository (unverified and planned count against it) */
export const progress = (p: Project) => shipped(p).length / Math.max(1, p.milestones.length);
export const currentMilestone = (p: Project) => p.milestones.find((m) => !SHIPPED.includes(m.evidence));
